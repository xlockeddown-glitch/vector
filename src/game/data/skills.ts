import type { CardDef, SetId } from "../types";

type SkillSpec = {
  id: string;
  name: string;
  craftId: string;
  set: SetId | null;
  blurb: string;
  kit: NonNullable<CardDef["kit"]>;
};

function skill(spec: SkillSpec): CardDef {
  return {
    id: spec.id,
    name: spec.name,
    kind: "kit",
    rarity: "rare",
    art: spec.craftId,
    set: spec.set,
    cost: 0,
    blurb: spec.blurb,
    kit: { ...spec.kit, craftId: spec.craftId },
  };
}

